class TestDebPackage(unittest.TestCase):
    def test_deb_structure(self) -> None:
        with tempfile.TemporaryDirectory() as d:
            deb = Path(d) / "x.deb"
            payload = {"opt/meridian-fracture/MeridianFracture.x86_64": (b"\x7fELF-binary", 0o755),
                       "opt/meridian-fracture/MeridianFracture.pck": (b"pck", 0o644),
                       "usr/share/applications/meridian-fracture.desktop": (package_linux.DESKTOP.encode(), 0o644)}
            package_linux.build_deb(deb, "9.9.9", payload)
            blob = deb.read_bytes()
            self.assertTrue(blob.startswith(b"!<arch>\n"))
            members, pos = {}, 8
            order = []
            while pos < len(blob):
                hdr = blob[pos:pos + 60]
                name = hdr[:16].decode().strip().rstrip("/")
                size = int(hdr[48:58].decode().strip())
                self.assertEqual(hdr[58:60], b"`\n")
                members[name] = blob[pos + 60:pos + 60 + size]
                order.append(name)
                pos += 60 + size + (size % 2)
            self.assertEqual(order, ["debian-binary", "control.tar.gz", "data.tar.gz"])
            self.assertEqual(members["debian-binary"], b"2.0\n")
            with tarfile.open(fileobj=io.BytesIO(members["control.tar.gz"])) as tf:
                control = tf.extractfile("./control").read().decode()
                self.assertIn("Package: meridian-fracture", control)
                self.assertIn("Version: 9.9.9", control)
                self.assertIn("Architecture: amd64", control)
                self.assertEqual(tf.getmember("./postinst").mode, 0o755)
            with tarfile.open(fileobj=io.BytesIO(members["data.tar.gz"])) as tf:
                names = tf.getnames()
                self.assertIn("./opt/meridian-fracture/MeridianFracture.x86_64", names)
                self.assertEqual(tf.getmember("./opt/meridian-fracture/MeridianFracture.x86_64").mode, 0o755)
                link = tf.getmember("./usr/bin/meridian-fracture")
                self.assertTrue(link.issym())
                self.assertEqual(link.linkname, "/opt/meridian-fracture/MeridianFracture.x86_64")
                self.assertEqual(tf.getmember("./opt/meridian-fracture/MeridianFracture.pck").uname, "root")

    def test_icon_is_a_valid_png(self) -> None:
        png = package_linux.make_icon(64)
        self.assertTrue(png.startswith(b"\x89PNG\r\n\x1a\n"))
        self.assertTrue(png.endswith(b"IEND\xaeB`\x82"))


