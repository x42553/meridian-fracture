class TestRWLock(unittest.TestCase):
    def run_py(self, code: str, tmp: Path) -> subprocess.Popen:
        prelude = f"import sys, time; sys.path.insert(0, {str(PY)!r}); from gdlib import locks; from pathlib import Path; L = locks.RWLock(Path({str(tmp)!r}))\n"
        return subprocess.Popen([sys.executable, "-c", prelude + code], stdout=subprocess.PIPE, text=True)

    def test_shared_holders_overlap(self) -> None:
        with tempfile.TemporaryDirectory() as d:
            tmp = Path(d)
            code = "with L.shared():\n    print('in', flush=True); time.sleep(0.8)\n"
            procs = [self.run_py(code, tmp) for _ in range(3)]
            t0 = time.time()
            for p in procs:
                self.assertEqual(p.stdout.readline().strip(), "in")
            self.assertLess(time.time() - t0, 0.7, "three shared holders must be inside at the same time")
            for p in procs:
                p.wait()
                p.stdout.close()

    def test_exclusive_excludes_shared(self) -> None:
        with tempfile.TemporaryDirectory() as d:
            tmp = Path(d)
            holder = self.run_py("with L.exclusive('test'):\n    print('locked', flush=True); time.sleep(1.0)\n", tmp)
            self.assertEqual(holder.stdout.readline().strip(), "locked")
            t0 = time.time()
            with locks.RWLock(tmp).shared():
                waited = time.time() - t0
            holder.wait()
            holder.stdout.close()
            self.assertGreater(waited, 0.6, "shared must wait for the exclusive holder")

    def test_waiting_importer_is_not_starved_by_new_readers(self) -> None:
        with tempfile.TemporaryDirectory() as d:
            tmp = Path(d)
            reader = self.run_py("with L.shared():\n    print('r', flush=True); time.sleep(1.5)\n", tmp)
            self.assertEqual(reader.stdout.readline().strip(), "r")
            t0 = time.time()
            writer = self.run_py("with L.exclusive():\n    print('w', time.time(), flush=True); time.sleep(0.2)\n", tmp)
            time.sleep(0.4)  # the writer is now queued behind the running reader
            late = self.run_py("with L.shared():\n    print('l', time.time(), flush=True)\n", tmp)
            w = float(writer.stdout.readline().split()[1])
            l_ = float(late.stdout.readline().split()[1])
            for p in (reader, writer, late):
                p.wait()
                p.stdout.close()
            self.assertLess(w, l_, "a reader that arrives after a queued writer must not overtake it")
            self.assertGreater(w - t0, 1.2, "writer had to wait for the running reader")


class TestTracking(unittest.TestCase):
    def test_snapshot_reacts_only_to_what_the_import_cache_needs(self) -> None:
        with tempfile.TemporaryDirectory() as d:
            game = Path(d)
            (game / "src").mkdir()
            cache = game.parent / "sig.json"
            klass = game / "src" / "a.gd"
            klass.write_text("class_name Alpha\nextends RefCounted\n\nfunc f() -> int:\n\treturn 1\n")
            plain = game / "src" / "plain.gd"
            plain.write_text("extends RefCounted\n")
            base = tracking.snapshot(game, cache)
            self.assertEqual(sorted(base), ["src/a.gd"], "scripts without class_name are irrelevant to the class cache")
            (game / "src" / "a.gd.uid").write_text("uid://x")             # generated by the editor: ignored
            (game / ".godot").mkdir()
            (game / ".godot" / "junk.tscn").write_text("x")               # cache dir: ignored
            (game / "notes.md").write_text("x")                           # untracked extension
            self.assertEqual(tracking.snapshot(game, cache), base)
            klass.write_text("class_name Alpha\nextends RefCounted\n\nfunc f() -> int:\n\treturn 2  # body edit\n")
            self.assertEqual(tracking.snapshot(game, cache), base, "a body-only edit needs no import")
            plain.write_text("extends RefCounted\nfunc g() -> void:\n\tpass\n")
            self.assertEqual(tracking.snapshot(game, cache), base, "neither does editing a script without class_name")
            klass.write_text("class_name Alpha\nextends Node\n")
            changed = tracking.snapshot(game, cache)
            self.assertNotEqual(changed, base, "a changed `extends` header does")
            klass.write_text("class_name Beta\nextends Node\n")
            self.assertNotEqual(tracking.snapshot(game, cache), changed, "so does a rename")
            (game / "src" / "b.gd").write_text("class_name Gamma\n")
            self.assertIn("src/b.gd", tracking.snapshot(game, cache))
            (game / "src" / "b.gd").unlink()
            self.assertNotIn("src/b.gd", tracking.snapshot(game, cache))  # deletions count too
            scene = game / "src" / "s.tscn"
            scene.write_text("[gd_scene]\n")
            s1 = tracking.snapshot(game, cache)
            scene.write_text("[gd_scene]\n# edited\n")
            self.assertNotEqual(tracking.snapshot(game, cache), s1, "scenes/assets are tracked by mtime+size")

    def test_import_state_staleness_and_reason(self) -> None:
        with tempfile.TemporaryDirectory() as d:
            game = Path(d) / "game"
            (game / ".godot").mkdir(parents=True)
            (game / "x.gd").write_text("class_name X\n")
            binary = Path(d) / "godot"
            binary.write_text("bin")
            st = tracking.ImportState(Path(d) / "state.json", game, binary)
            self.assertTrue(st.is_stale()[0])
            st.save(st.snapshot(), 0.1)
            self.assertTrue(st.is_stale()[0], "class cache file missing -> stale")
            (game / ".godot" / "global_script_class_cache.cfg").write_text("list=[]")
            self.assertEqual(st.is_stale(), (False, "up to date"))
            (game / "x.gd").write_text("class_name X\n# body\n")
            self.assertEqual(st.is_stale(), (False, "up to date"))
            (game / "y.gd").write_text("class_name Y\n")
            stale, why = st.is_stale()
            self.assertTrue(stale)
            self.assertIn("new: y.gd", why)


