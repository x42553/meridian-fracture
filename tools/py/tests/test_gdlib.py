class TestXplatCompare(unittest.TestCase):
    def test_identical_and_divergent(self) -> None:
        a = [(20, "aa"), (40, "bb"), (60, "cc")]
        self.assertIsNone(xplat_determinism.compare({"mac": a, "linux": list(a)}))
        b = [(20, "aa"), (40, "bb"), (60, "XX")]
        msg = xplat_determinism.compare({"mac": a, "linux": b})
        self.assertIn("tick 60", msg)
        self.assertIn("last tick where all targets agreed: 40", msg)
        short = xplat_determinism.compare({"mac": a, "linux": a[:2]})
        self.assertIn("chain ended earlier", short)

    def test_parse_chain(self) -> None:
        text = "noise\nHASH tick=20 DEADbeef\nHASH tick=40 01\nSCENARIO_DONE\n"
        self.assertEqual(xplat_determinism.parse_chain(text), [(20, "deadbeef"), (40, "01")])


class TestLinuxSync(unittest.TestCase):
    def test_mirror_copy_delete_and_keep_godot(self) -> None:
        with tempfile.TemporaryDirectory() as d:
            src, dst = Path(d) / "src", Path(d) / "dst"
            (src / "a").mkdir(parents=True)
            (src / "a" / "x.gd").write_text("1")
            (src / ".godot").mkdir()
            (src / ".godot" / "host_cache").write_text("host")
            copied, deleted, total = linuxrun.sync_tree(src, dst)
            self.assertEqual((copied, deleted, total), (1, 0, 1))
            self.assertFalse((dst / ".godot").exists(), "host .godot must never be mirrored")
            (dst / ".godot").mkdir()
            (dst / ".godot" / "linux_cache").write_text("keep")
            (dst / "stale.gd").write_text("gone from source")
            (src / "a" / "x.gd").write_text("22")
            copied, deleted, _ = linuxrun.sync_tree(src, dst)
            self.assertEqual((copied, deleted), (1, 1))
            self.assertEqual((dst / "a" / "x.gd").read_text(), "22")
            self.assertFalse((dst / "stale.gd").exists())
            self.assertTrue((dst / ".godot" / "linux_cache").exists(), "the container's own .godot survives a sync")
            self.assertEqual(linuxrun.sync_tree(src, dst)[:2], (0, 0), "second sync is a no-op")


