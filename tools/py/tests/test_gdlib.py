class TestSyncBible(unittest.TestCase):
    def test_copy_refuse_force_and_check(self) -> None:
        with tempfile.TemporaryDirectory() as d:
            src, dst = Path(d) / "in", Path(d) / "out"
            src.mkdir()
            for n in sync_bible.FILES:
                (src / n).write_text(json.dumps({"name": n}))
            old = (sync_bible.SRC_DIR, sync_bible.DST_DIR)
            sync_bible.SRC_DIR, sync_bible.DST_DIR = src, dst
            quiet = contextlib.ExitStack()
            quiet.enter_context(contextlib.redirect_stdout(io.StringIO()))
            quiet.enter_context(contextlib.redirect_stderr(io.StringIO()))
            try:
                self.assertEqual(sync_bible.sync(False), 0)
                self.assertEqual(sync_bible.check(), 0)
                for n in sync_bible.FILES:
                    self.assertEqual((src / n).read_bytes(), (dst / n).read_bytes())
                self.assertTrue((dst / "README.md").read_text().startswith("# game/data/bible - GENERATED, DO NOT EDIT"))
                (dst / sync_bible.FILES[0]).write_text("hand edit")
                self.assertEqual(sync_bible.check(), 1)
                self.assertEqual(sync_bible.sync(False), 1, "must refuse to clobber a hand edit")
                self.assertEqual((dst / sync_bible.FILES[0]).read_text(), "hand edit")
                self.assertEqual(sync_bible.sync(True), 0)
                self.assertEqual(sync_bible.check(), 0)
                (src / sync_bible.FILES[1]).write_text("changed upstream")
                self.assertEqual(sync_bible.check(), 1, "stale mirror must be detected")
                self.assertEqual(sync_bible.sync(False), 0, "an untouched mirror follows Input/")
            finally:
                quiet.close()
                sync_bible.SRC_DIR, sync_bible.DST_DIR = old


